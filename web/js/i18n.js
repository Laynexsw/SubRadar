  function srNorm(s) { return (s || '').replace(/\s+/g, ' ').trim(); }
  function srDict() { return srLang === 'de' ? SR_I18N_DE : SR_I18N; }
  function t(tr) { if (srLang === 'tr') return tr; const d = srDict(); return d[srNorm(tr)] || tr; }
  function srSwapTextNode(node) {
    const m = node.nodeValue.match(/^(\s*)([\s\S]*?)(\s*)$/);
    if (!m || !srNorm(m[2])) return;
    if (node._trRaw === undefined) node._trRaw = m[2];
    const en = srDict()[srNorm(node._trRaw)];
    if (!en) return;
    node.nodeValue = m[1] + (srLang === 'tr' ? node._trRaw : en) + m[3];
  }
  function srApplyLang(scope) {
    const root = scope || document;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, { acceptNode(n) {
      if (!n.nodeValue || !n.nodeValue.trim()) return NodeFilter.FILTER_REJECT;
      const p = n.parentElement;
      if (!p) return NodeFilter.FILTER_REJECT;
      const tag = p.tagName;
      if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'NOSCRIPT') return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    }});
    const nodes = []; let n;
    while ((n = walker.nextNode())) nodes.push(n);
    nodes.forEach(srSwapTextNode);
    const quads = root.querySelectorAll ? Array.from(root.querySelectorAll('[placeholder],[aria-label]')) : [];
    quads.forEach(el => {
      ['placeholder', 'aria-label'].forEach(attr => {
        if (!el.hasAttribute(attr)) return;
        const store = attr === 'placeholder' ? '_trPh' : '_trAria';
        if (el[store] === undefined) el[store] = el.getAttribute(attr) || '';
        const en = srDict()[srNorm(el[store])];
        if (en) el.setAttribute(attr, srLang === 'tr' ? el[store] : en);
      });
    });
    document.documentElement.lang = srLang;
    document.title = SR_TITLE[srLang];
    const md = document.querySelector('meta[name="description"]');
    if (md) md.setAttribute('content', SR_META[srLang]);
  }
  function srPaintLangButtons() {
    document.querySelectorAll('.lang-btn').forEach(b => {
      const active = b.dataset.lang === srLang.toUpperCase();
      b.setAttribute('aria-pressed', String(active));
      b.classList.toggle('bg-white/15', active);
      b.classList.toggle('text-white', active);
      b.classList.toggle('text-white/50', !active);
    });
  }
